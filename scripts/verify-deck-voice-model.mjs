import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base=process.env.VOICE_FACTORY_DESIGNER_URL??'http://127.0.0.1:8091';
const origin=new URL(base);
assert.ok(origin.protocol==='http:'&&['127.0.0.1','localhost'].includes(origin.hostname)&&['8091','8191'].includes(origin.port)&&origin.pathname==='/'&&!origin.username&&!origin.password&&!origin.search&&!origin.hash,'Model verification requires an isolated local designer');
const send=async(path,body,method='POST')=>{const r=await fetch(base+path,{method,headers:{'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body),signal:AbortSignal.timeout(40000)});const data=await r.json();return {status:r.status,data};};
const wait=async(fn)=>{const deadline=Date.now()+65000;while(!await fn()){if(Date.now()>deadline)throw Error('Timed out');await new Promise(r=>setTimeout(r,100));}};
const report={scope:'local-model-generated-deck-editing',results:[]};
await send('/editor/intent/prepare',{});
await wait(async()=>{const r=await send('/editor/intent/model',undefined,'GET');return r.data.state==='ready';});
const {data:copy}=await send('/library/vk-tech-shablon/copy');
assert.ok(copy.deck_id);
const path=`/decks/${copy.deck_id}`;
report.deckId=copy.deck_id;
const read=async()=>{const r=await send(path,undefined,'GET');assert.equal(r.status,200);return r.data.variants.a;};
const original=await read(),element=original.scenes[0].elements.find(e=>e.type==='text'&&e.role==='title');
assert.ok(element);
const rewrite=(id,instruction)=>send(path+'/a/slides/1/voice-rewrite',{request_id:id,element_id:element.id,instruction});
let started=performance.now();
const done=await rewrite(crypto.randomUUID(),'Сократи заголовок до пяти слов. Только текст, сохрани смысл.');
assert.equal(done.status,200,JSON.stringify(done.data));assert.ok(done.data.state);
let current=await read(),changed=current.scenes[0].elements.find(e=>e.id===element.id);
assert.notEqual(changed.text,element.text);assert.equal(changed.text,done.data.state.scenes[0].elements.find(e=>e.id===element.id).text);
report.results.push({name:'warm-rewrite-persists',result:'PASS',ms:Math.round(performance.now()-started),modelMs:done.data.elapsed_ms,before:element.text,after:changed.text});
let id=crypto.randomUUID();
const pending=rewrite(id,'Перепиши выбранный текст деловым языком, сохрани факты.');
await wait(async()=>{const r=await send('/editor/intent/status',undefined,'GET');return r.data.active>0;});
started=performance.now();
const quick=await send(path+'/a/slides/1/text',{element_id:element.id,text:'Ручная правка важнее запоздалого ответа.'},'PATCH');assert.equal(quick.status,200);
const fastMs=Math.round(performance.now()-started),stale=await pending;
assert.equal(stale.status,409,JSON.stringify(stale.data));
current=await read();assert.equal(current.scenes[0].elements.find(e=>e.id===element.id).text,'Ручная правка важнее запоздалого ответа.');
report.results.push({name:'fast-edit-while-model-running',result:'PASS',fastMs,staleStatus:stale.status});
id=crypto.randomUUID();const cancelled=rewrite(id,'Сократи выбранный текст до двух слов.');
await wait(async()=>{const r=await send('/editor/intent/status',undefined,'GET');return r.data.active>0;});
started=performance.now();await send(`/editor/intent/${id}/cancel`,{});const cancelledResult=await cancelled;
assert.equal(cancelledResult.status,409);assert.deepEqual((await read()).scenes,current.scenes);
report.results.push({name:'cancel-without-mutation',result:'PASS',ms:Math.round(performance.now()-started)});
report.result='PASS';
await fs.mkdir(new URL('../.voice-factory/',import.meta.url),{recursive:true});
await fs.writeFile(new URL('../.voice-factory/model-acceptance.json',import.meta.url),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
