const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..'),out=path.join(root,'artifacts/stage2-demo');
let activeBrowser;
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 activeBrowser=browser;
 const context=await browser.newContext({viewport:{width:1600,height:1000},acceptDownloads:true});
 const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 const did='6b57bd92f26041b78f94df1706d2a80a';
 const state=await (await context.request.get('http://localhost:8090/decks/'+did)).json();
 const ref=state.variants.a.plan.slides.findIndex(s=>s.provenance?.file_name==='reference_201.csv');
 await page.goto('http://localhost:8088/#/decks/'+did+'/edit/a');
 await page.locator('.edit-thumb').first().waitFor();
 await page.locator('.edit-thumb').nth(ref).click();
 await page.locator('.edit-slide-img').waitFor();
 await page.waitForTimeout(1500);await page.screenshot({path:path.join(out,'reference-compact-editor.png')});
 await page.getByRole('button',{name:'Скачать: pptx, pdf или html'}).click();
 assert(await page.locator('a[href$="deck.sources.zip"]').count());
 assert(await page.locator('a[href$="deck.bundle.zip"]').count());
 const download=page.waitForEvent('download');await page.locator('a[href$="deck.sources.zip"]').click();
 const downloaded=await download;assert.equal(await downloaded.failure(),null);
 await downloaded.saveAs(path.join(out,'reference-browser.sources.zip'));
 await page.goto('file:///'+path.join(out,'Все презентации — компактно','Education — A.html').replaceAll('\\','/'));
 await page.locator('#source-access > details > summary').click();
 await page.locator('#source-filter').fill('REF-201');
 const table=page.locator('.source-dataset').filter({has:page.locator('summary', {hasText:'reference_201.csv'})});
 assert.equal(await table.locator('tbody tr:visible').count(),1);
 assert((await table.locator('tbody tr:visible').innerText()).includes('REF-201'));
 await page.screenshot({path:path.join(out,'reference-offline-search.png')});
 const originalDownload=page.waitForEvent('download');await table.getByRole('link',{name:'Скачать оригинал'}).click();
 const original=await originalDownload;await original.saveAs(path.join(out,'reference-browser-original.csv'));
 assert(fs.readFileSync(path.join(out,'reference-browser-original.csv')).equals(fs.readFileSync(path.join(out,'content-v2/reference_201.csv'))));
 await page.locator('#source-filter').fill('');assert.equal(await table.locator('tbody tr:visible').count(),201);
 await page.goto('http://localhost:8088/#/?ds=shablon-prezentacii-vk-education-5');
 await page.locator('.semantic-plan input[type=file]').setInputFiles(path.join(out,'content-v2/reference_201.csv'));
 await page.getByRole('button',{name:'Проанализировать',exact:true}).click();
 await page.getByRole('radio',{name:/Кратко/}).waitFor({timeout:60000});
 assert(await page.getByRole('radio',{name:/Кратко/}).isChecked());
 await page.getByRole('radio',{name:/Полностью/}).check();
 assert(await page.getByRole('radio',{name:/Полностью/}).isChecked());
 assert((await page.locator('.semantic-plan').innerText()).includes('29 слайдов'));
 await page.screenshot({path:path.join(out,'reference-display-choice.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(out,'reference-compact-browser.json'),JSON.stringify({status:'passed',errors,offlineSearch201:true,originalExactBytes:true,compactDefault:true,fullMode29Pages:true,sourceDownload:true},null,2));
 await browser.close();console.log('Browser checks passed');
})().catch(async e=>{console.error(e);if(activeBrowser)await activeBrowser.close();process.exit(1)});
