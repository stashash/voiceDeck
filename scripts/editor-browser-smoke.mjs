import {createRequire} from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const base=process.env.EDITOR_TEST_URL||'http://127.0.0.1:5173';
const output=path.resolve('.codex-build/editor-verification');
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',error=>errors.push(String(error)));
page.on('response',response=>{if(response.status()>=500)errors.push(response.status()+' '+response.url());});
const command=async value=>{
 await page.getByRole('textbox',{name:'Голосовая команда текстом'}).fill(value);
 await page.getByRole('button',{name:'Выполнить',exact:true}).click();
};
try{
 await page.goto(base+'/#/editor');
 await page.getByRole('textbox',{name:'Голосовая команда текстом'}).waitFor();
 await page.getByRole('textbox',{name:'Название документа'}).fill('Проверка голосового редактора');
 await command('Добавь заголовок План запуска и две карточки: Продукт и Продажи');
 await page.waitForFunction(()=>document.querySelectorAll('.canvas-component').length===3);
 assert.deepEqual(await page.locator('.canvas-component>div').allTextContents(),['План запуска','Продукт','Продажи']);
 await page.getByRole('button',{name:'Выбрать номер 2',exact:true}).click();
 const before=await page.locator('.canvas-component').nth(1).evaluate(el=>el.style.left);
 let pending;
 await page.route('**/editor/intent',route=>{pending=route;});
 await command('Разработай новое оформление');
 await page.waitForFunction(()=>document.body.textContent.includes('Обработка · очередь'));
 await command('Вправо на 20');
 const after=await page.locator('.canvas-component').nth(1).evaluate(el=>el.style.left);
 assert.notEqual(after,before);
 await command('Стоп');
 if(pending)await pending.fulfill({status:200,contentType:'application/json',body:JSON.stringify({operations:[{op:'delete',targets:['all']}],clarification:'',summary:'Late'})}).catch(()=>{});
 await page.unroute('**/editor/intent');
 assert.equal(await page.locator('.canvas-component').count(),3);
 await page.getByRole('button',{name:'Сохранить',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Сохранено'}).waitFor();
 await page.reload();
 await page.getByRole('textbox',{name:'Голосовая команда текстом'}).waitFor();
 assert.equal(await page.locator('.canvas-component').count(),3);
 assert.equal(await page.locator('.canvas-component').nth(1).evaluate(el=>el.style.left),after);
 await command('Новый слайд');
 await command('Добавь таблицу 2 на 2');
 await command('Ячейка 2, 1: Выручка');
 assert.equal(await page.getByRole('textbox',{name:'Ячейка 2, 1',exact:true}).inputValue(),'Выручка');
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'PPTX',exact:true}).click();
 const download=await downloadPromise;await download.saveAs(path.join(output,'editor-smoke.pptx'));
 await command('Выбери слайд один');
 await page.getByRole('button',{name:'Сохранить',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Сохранено'}).waitFor();
 await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
 const layout=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,canvas:document.querySelector('.component-canvas').getBoundingClientRect().toJSON()}));
 assert.ok(layout.scroll<=layout.width+1,JSON.stringify(layout));
 assert.ok(layout.canvas.width>250);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({result:'PASS',checks:['compound-command','local-while-model-pending','cancel-late-answer','save-reload','table-cell','native-pptx-download','desktop-mobile-layout'],layout,output}));
}finally{await browser.close();}
